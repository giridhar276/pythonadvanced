# Example: Prepare an employee profile for HR.
name = "Anita Rao"
emp_id = 104
salary = 48500.50
is_active = True

print("Employee:", name)
print("Employee ID:", emp_id)
print("Monthly salary:", salary)
print("Currently active:", is_active)

# Reassign a variable after a salary revision.
salary = salary + 2500
print("Revised salary:", salary)

# Check the types of values stored.
print("Name type:", type(name))
print("Salary type:", type(salary))
print("Status type:", type(is_active))
